from typing import Protocol
from uuid import UUID

from ...domain.entities.role import Role
from ...domain.entities.role_assignment import RoleAssignment


class IAccessControlRepository(Protocol):
    def find_role(self, role_id: UUID) -> Role | None: ...
    def find_role_by_name(self, name: str) -> Role | None: ...
    def save_role(self, role: Role) -> None: ...
    def find_assignment(self, assignment_id: UUID) -> RoleAssignment | None: ...
    def find_active_assignment(self, user_id: UUID, role_id: UUID, scope_id: UUID) -> RoleAssignment | None: ...
    def save_assignment(self, assignment: RoleAssignment) -> None: ...
    def permissions_for(self, user_id: UUID, scope_type: str, scope_id: UUID | None) -> frozenset[str]: ...


class IPermissionCatalog(Protocol):
    def declared_permissions(self) -> frozenset[str]: ...


class IPermissionCache(Protocol):
    def get(self, user_id: UUID, permission: str, scope_key: str) -> bool | None: ...
    def set(self, user_id: UUID, permission: str, scope_key: str, allowed: bool) -> None: ...
    def invalidate_all(self) -> None: ...


class IAccessControlOutbox(Protocol):
    def add(self, event: object) -> None: ...


class IAccessControlUnitOfWork(Protocol):
    def __enter__(self) -> "IAccessControlUnitOfWork": ...
    def __exit__(self, exception_type, exception, traceback) -> bool | None: ...


class IAccessControlClock(Protocol):
    def now_utc(self): ...


class IProcessedEventRepository(Protocol):
    def has_processed(self, event_id: UUID, consumer_name: str) -> bool: ...
    def mark_processed(self, event_id: UUID, consumer_name: str) -> None: ...