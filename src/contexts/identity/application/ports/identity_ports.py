from typing import Protocol
from uuid import UUID

from ...domain.entities.merchant import Merchant
from ...domain.entities.user import User
from shared_kernel.ports import IConnectionUsageReader


class IUserRepository(Protocol):
    def find_by_phone(self, phone_number: str) -> User | None: ...
    def find_by_id(self, user_id: UUID) -> User | None: ...
    def save(self, user: User) -> None: ...


class IMerchantRepository(Protocol):
    def find_by_id(self, merchant_id: UUID) -> Merchant | None: ...
    def save(self, merchant: Merchant) -> None: ...


class IPasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


class ITokenService(Protocol):
    def issue_tokens(self, user_id: UUID) -> dict: ...
    def issue_access_token(self, user_id: UUID) -> dict: ...
    def refresh_access_token(self, refresh_token: str) -> dict: ...


class IIdentityOutbox(Protocol):
    def add(self, event: object) -> None: ...


class IIdentityUnitOfWork(Protocol):
    def __enter__(self) -> "IIdentityUnitOfWork": ...
    def __exit__(self, exception_type, exception, traceback) -> bool | None: ...


